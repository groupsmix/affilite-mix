#!/usr/bin/env node
/**
 * audit5-#27 — fail-fast guard for unresolved `${...}` shell-style
 * placeholders in any rendered wrangler config.
 *
 * Background:
 *   `wrangler.jsonc` ships with `"id": "${RATE_LIMIT_KV_NAMESPACE_ID}"`
 *   placeholders so the file can be committed without leaking an
 *   environment-specific namespace ID. Wrangler itself does NOT perform
 *   shell-style env substitution — the CI workflow inlines real IDs via
 *   `perl -i -0pe` (deploy.yml) or by generating `wrangler.preview.json`
 *   plus a per-job inline step (preview.yml).
 *
 *   If either pipeline forgets to run that substitution — e.g., a
 *   future refactor introduces a third deploy path, or a contributor
 *   runs `wrangler deploy` locally without the env block — wrangler
 *   happily ships the literal string `${RATE_LIMIT_KV_NAMESPACE_ID}`
 *   as the namespace ID, which then fails opaquely at request time
 *   with a "namespace not found" error.
 *
 *   This script grepts every wrangler config it can find for an
 *   unresolved `${SCREAMING_SNAKE_CASE}` token and exits non-zero with
 *   a useful diagnostic if one survived. Wire it into deploy.yml /
 *   preview.yml AFTER the substitution step but BEFORE the actual
 *   `wrangler deploy` / `opennextjs-cloudflare deploy`.
 *
 * Usage:
 *   node scripts/check-wrangler-placeholders.mjs [path ...]
 *
 *   With no args, checks the default set:
 *     wrangler.jsonc       — the committed config (placeholders are
 *                            EXPECTED here; the script treats this
 *                            file as advisory unless `--strict` is
 *                            passed)
 *     wrangler.preview.json — generated by scripts/generate-preview-wrangler.cjs
 *     wrangler.deploy.json  — optional, if a future job emits one
 *
 * Flags:
 *   --strict   Also fail on placeholders in `wrangler.jsonc`. Use this
 *              flag only in deploy.yml AFTER `inline_kv_id` has run.
 */

import { existsSync, readFileSync } from "node:fs";
import { resolve, basename } from "node:path";

const args = process.argv.slice(2);
const strict = args.includes("--strict");
const explicitPaths = args.filter((a) => !a.startsWith("--"));

const DEFAULTS = ["wrangler.jsonc", "wrangler.preview.json", "wrangler.deploy.json"];

const paths = explicitPaths.length > 0 ? explicitPaths : DEFAULTS;

// Match `${NAME}` tokens but not `$NAME` or `$1` (positional args) or
// JSON-pointer fragments. SCREAMING_SNAKE_CASE only — wrangler bindings
// are conventionally all-caps.
const PLACEHOLDER_RE = /\$\{([A-Z][A-Z0-9_]*)\}/g;

let failed = false;
let checked = 0;

for (const rel of paths) {
  const abs = resolve(process.cwd(), rel);
  if (!existsSync(abs)) {
    if (explicitPaths.length > 0) {
      console.error(`[check-wrangler-placeholders] missing file: ${rel}`);
      failed = true;
    }
    // Default-set files that don't exist (e.g. wrangler.deploy.json
    // when no such pipeline runs) are skipped silently.
    continue;
  }

  checked++;
  const raw = readFileSync(abs, "utf8");
  const found = new Set();
  let m;
  PLACEHOLDER_RE.lastIndex = 0;
  while ((m = PLACEHOLDER_RE.exec(raw)) !== null) {
    found.add(m[1]);
  }

  if (found.size === 0) continue;

  const isAdvisory = basename(abs) === "wrangler.jsonc" && !strict;
  const label = isAdvisory ? "warn" : "error";
  const prefix = isAdvisory ? "::warning::" : "::error::";

  for (const name of found) {
    console.error(
      `${prefix}[check-wrangler-placeholders] unresolved \${${name}} in ${rel}`,
    );
  }
  console.error(
    `${prefix}[check-wrangler-placeholders] ${found.size} unresolved placeholder(s) ` +
      `in ${rel} (level=${label}).`,
  );
  console.error(
    `  Hint: this file was expected to have ALL \${...} placeholders ` +
      `substituted before \`wrangler deploy\` runs. Check the CI ` +
      `workflow's inline step (\`inline_kv_id\` in deploy.yml, the ` +
      `dummy-KV-ID step in preview.yml, or the \`--strict\` flag flow ` +
      `for wrangler.jsonc itself).`,
  );

  if (!isAdvisory) {
    failed = true;
  }
}

if (checked === 0) {
  console.error(
    "[check-wrangler-placeholders] no wrangler config files found — pass at least one path.",
  );
  process.exit(2);
}

if (failed) {
  process.exit(1);
}

console.log(
  `[check-wrangler-placeholders] OK — ${checked} file(s) free of unresolved \${...} placeholders.`,
);

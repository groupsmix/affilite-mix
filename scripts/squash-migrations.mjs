#!/usr/bin/env node
/**
 * A-014: Migration squash baseline script.
 *
 * Squashes all numbered SQL migrations in `supabase/migrations/` into a
 * single ordered baseline file. This baseline can be used to speed up
 * fresh environment provisioning (CI, new team members) by running one
 * large SQL file instead of N individual migrations.
 *
 * Usage:
 *   node scripts/squash-migrations.mjs [--out=supabase/migrations/baseline.sql]
 *
 * Cadence: run this script after every N new migrations or before a
 * major release, then commit the resulting baseline file. The baseline
 * is additive — existing environments continue applying new migrations
 * individually via their normal migration runner.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const MIGRATIONS_DIR = "supabase/migrations";
const DEFAULT_OUT = "supabase/migrations/baseline.sql";

async function main() {
  const outFile = process.argv.find((a) => a.startsWith("--out="))?.slice(6) ?? DEFAULT_OUT;

  const files = await readdir(MIGRATIONS_DIR);
  const sqlFiles = files
    .filter((f) => f.endsWith(".sql") && !f.endsWith("-down.sql"))
    .filter((f) => /^\d+_/.test(f))
    .sort((a, b) => {
      const na = parseInt(a.split("_")[0], 10);
      const nb = parseInt(b.split("_")[0], 10);
      return na - nb;
    });

  if (sqlFiles.length === 0) {
    console.error("No numbered migration files found in", MIGRATIONS_DIR);
    process.exit(1);
  }

  let baseline = `-- ============================================================\n`;
  baseline += `-- Baseline generated by squash-migrations.mjs\n`;
  baseline += `-- Contains ${sqlFiles.length} migrations (ordered)\n`;
  baseline += `-- Generated: ${new Date().toISOString()}\n`;
  baseline += `-- DO NOT EDIT MANUALLY — regenerate via: node scripts/squash-migrations.mjs\n`;
  baseline += `-- ============================================================\n\n`;

  for (const file of sqlFiles) {
    const content = await readFile(join(MIGRATIONS_DIR, file), "utf-8");
    baseline += `-- ── ${file} ───────────────────────────────────────────────\n`;
    baseline += content.trimEnd();
    baseline += "\n\n";
  }

  await writeFile(outFile, baseline, "utf-8");
  console.log(
    `Baseline written to ${outFile} (${sqlFiles.length} migrations, ${baseline.length} chars)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

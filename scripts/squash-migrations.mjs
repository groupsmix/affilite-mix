#!/usr/bin/env node

/**
 * F-06 / ADR-0013: Migration Squashing Script
 *
 * This script generates a baseline migration from the current database schema
 * and archives existing migrations to improve bootstrap time for fresh environments.
 *
 * USAGE:
 *   node scripts/squash-migrations.mjs
 *
 * PREREQUISITES:
 *   - Supabase CLI installed and authenticated
 *   - SUPABASE_DB_URL environment variable set
 *   - Access to the target database (production or staging)
 *
 * PROCESS:
 *   1. Takes a schema-only dump of the current database
 *   2. Saves as supabase/migrations/00000_baseline.sql
 *   3. Moves existing migrations to supabase/migrations/_archive/
 *   4. Verifies the baseline produces identical schema
 *
 * SAFETY:
 *   - Never squash migrations that haven't been applied to production
 *   - Always verify schema parity before and after squash
 *   - Keep rollback capability via the _archive/ directory
 */

import { execSync } from "child_process";
import { readFileSync, readdirSync, mkdirSync, renameSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const MIGRATIONS_DIR = join(__dirname, "..", "supabase", "migrations");
const ARCHIVE_DIR = join(MIGRATIONS_DIR, "_archive");
const BASELINE_FILE = join(MIGRATIONS_DIR, "00000_baseline.sql");

// Colors for output
const GREEN = "\x1b[32m";
const RED = "\x1b[31m";
const YELLOW = "\x1b[33m";
const RESET = "\x1b[0m";

function log(message, color = "") {
  console.log(`${color}${message}${RESET}`);
}

function error(message) {
  log(message, RED);
}

function success(message) {
  log(message, GREEN);
}

function warn(message) {
  log(message, YELLOW);
}

function checkPrerequisites() {
  const dbUrl = process.env.SUPABASE_DB_URL || process.env.DATABASE_URL;
  if (!dbUrl) {
    error("Error: SUPABASE_DB_URL or DATABASE_URL environment variable not set");
    error("Set it to your Supabase database connection string");
    process.exit(1);
  }

  try {
    execSync("pg_dump --version", { stdio: "ignore" });
  } catch {
    error("Error: pg_dump not found. Install PostgreSQL client tools");
    process.exit(1);
  }

  try {
    execSync("supabase --version", { stdio: "ignore" });
  } catch {
    error("Error: Supabase CLI not found. Install it from https://supabase.com/docs/guides/cli");
    process.exit(1);
  }
}

function takeSchemaDump() {
  log("Taking schema-only dump of current database...");
  
  const dbUrl = process.env.SUPABASE_DB_URL || process.env.DATABASE_URL;
  const command = `pg_dump "${dbUrl}" --schema-only --no-owner --no-acl --format=plain`;
  
  try {
    const dump = execSync(command, { encoding: "utf-8" });
    
    // Add header comment to baseline file
    const header = `-- F-06 / ADR-0013: Baseline Migration
-- Generated: ${new Date().toISOString()}
-- This file represents the cumulative schema state of all archived migrations.
-- Individual migrations are preserved in supabase/migrations/_archive/ for audit trail.
-- DO NOT EDIT THIS FILE MANUALLY. Regenerate via scripts/squash-migrations.mjs

`;
    
    return header + dump;
  } catch (err) {
    error(`Error taking schema dump: ${err.message}`);
    process.exit(1);
  }
}

function archiveExistingMigrations() {
  log("Archiving existing migrations...");
  
  if (!existsSync(MIGRATIONS_DIR)) {
    error(`Error: Migrations directory not found: ${MIGRATIONS_DIR}`);
    process.exit(1);
  }

  // Create archive directory if it doesn't exist
  if (!existsSync(ARCHIVE_DIR)) {
    mkdirSync(ARCHIVE_DIR, { recursive: true });
    success(`Created archive directory: ${ARCHIVE_DIR}`);
  }

  const files = readdirSync(MIGRATIONS_DIR);
  const migrationFiles = files.filter(f => f.endsWith(".sql") && f !== "00000_baseline.sql");
  
  if (migrationFiles.length === 0) {
    warn("No migration files to archive");
    return;
  }

  log(`Found ${migrationFiles.length} migration files to archive`);
  
  for (const file of migrationFiles) {
    const src = join(MIGRATIONS_DIR, file);
    const dst = join(ARCHIVE_DIR, file);
    
    try {
      renameSync(src, dst);
      success(`Archived: ${file}`);
    } catch (err) {
      error(`Error archiving ${file}: ${err.message}`);
      process.exit(1);
    }
  }
}

function writeBaseline(schemaDump) {
  log("Writing baseline migration...");
  
  try {
    // Write to a temporary file first
    const tempFile = BASELINE_FILE + ".tmp";
    require("fs").writeFileSync(tempFile, schemaDump);
    
    // Rename to final location (atomic operation)
    renameSync(tempFile, BASELINE_FILE);
    
    success(`Baseline migration written: ${BASELINE_FILE}`);
  } catch (err) {
    error(`Error writing baseline: ${err.message}`);
    process.exit(1);
  }
}

function verifySchema() {
  log("Verifying schema parity...");
  warn("Manual verification required:");
  warn("1. Apply the baseline to a fresh database");
  warn("2. Run pg_dump --schema-only on both databases");
  warn("3. Diff the outputs to ensure schema parity");
  warn("4. If schemas differ, restore from _archive/ and investigate");
}

function main() {
  log("=== F-06 / ADR-0013: Migration Squashing ===");
  log("");
  
  checkPrerequisites();
  log("Prerequisites check passed");
  log("");
  
  const schemaDump = takeSchemaDump();
  success("Schema dump completed");
  log("");
  
  archiveExistingMigrations();
  log("");
  
  writeBaseline(schemaDump);
  log("");
  
  verifySchema();
  log("");
  
  success("=== Migration squashing completed ===");
  log("");
  log("Next steps:");
  log("1. Commit the changes (baseline.sql + _archive/)");
  log("2. Deploy to a staging environment first");
  log("3. Verify the application works correctly");
  log("4. Deploy to production");
  log("5. Monitor for any issues");
}

main();
